using System.Runtime.InteropServices;

namespace SharpClip;

internal sealed class QueueEntry
{
    public QueueEntry(Guid id, ClipItem item)
    {
        Id = id;
        Item = item;
    }

    public Guid Id { get; }
    public ClipItem Item { get; }
}

/// <summary>
/// While the queue is on, every capture is appended and each real Ctrl+V pastes the next item.
/// Clipboard data is promised (delayed rendering). A read without a Ctrl+V puts the same item back.
/// </summary>
internal static class ClipQueue
{
    private static readonly object Gate = new();
    private static readonly List<QueueEntry> Entries = [];
    private static readonly string[] Markers =
    [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
    ];

    private static IntPtr _hwnd;
    private static QueueWindow? _window;
    private static List<ClipPayload> _promised = [];
    private static ClipItem? _placed;
    private static int _placement;
    private static int _handledPlacement;
    private static long _placedAt;
    private static uint _sequence;
    private static bool _replacing;
    private static bool _placedAgain;
    private static int _replaceStreak;
    private static long _lastKeyDown = -1;
    private static long _lastActivation = -10_000;
    private static Timer? _timer;

    public static bool IsActive { get; private set; }
    public static bool PastesNewestFirst { get; private set; }
    public static int Count => Entries.Count;

    public static IReadOnlyList<QueueEntry> PasteOrder
    {
        get
        {
            lock (Gate)
            {
                return PastesNewestFirst ? Entries.AsEnumerable().Reverse().ToList() : Entries.ToList();
            }
        }
    }

    public static void Bind(IntPtr hwnd) => _hwnd = hwnd;

    public static void NoteKeyDown() => _lastKeyDown = Environment.TickCount64;

    public static void NoteActivation() => _lastActivation = Environment.TickCount64;

    public static void Toggle()
    {
        if (IsActive) Stop();
        else Start();
    }

    public static void Start()
    {
        if (IsActive) return;
        lock (Gate)
        {
            IsActive = true;
            Entries.Clear();
            _placed = null;
            _promised = [];
        }
        _window ??= new QueueWindow();
        _window.Update();
        _window.ShowQueue();
    }

    public static void Stop()
    {
        ClipItem? placed;
        var owns = false;
        lock (Gate)
        {
            if (!IsActive && Entries.Count == 0) 
            {
                _window?.HideQueue();
                return;
            }
            IsActive = false;
            placed = _placed;
            owns = OwnsLocked();
            Entries.Clear();
            _placed = null;
            _promised = [];
            _placement++;
        }
        _timer?.Dispose();
        _timer = null;
        if (owns && placed is not null)
        {
            ClipboardCapture.Place(placed, SettingsStore.Current.AlwaysPlainText);
        }
        _window?.HideQueue();
    }

    public static void SetNewestFirst(bool newest)
    {
        PastesNewestFirst = newest;
        if (!IsActive) return;
        _window?.Update();
        LineUp();
    }

    public static void Push(ClipItem item)
    {
        if (!IsActive) return;
        lock (Gate)
        {
            Entries.Add(new QueueEntry(Guid.NewGuid(), item.Detach()));
        }
        _window?.Update();
        LineUp();
    }

    public static void PlaceNow()
    {
        List<ClipPayload> payloads;
        var placement = 0;
        lock (Gate)
        {
            if (!IsActive || _promised.Count == 0 || _hwnd == IntPtr.Zero) return;
            payloads = _promised.ToList();
            placement = _placement;
            _placedAgain = _replacing;
            if (!_placedAgain) _replaceStreak = 0;
        }
        ClipboardCapture.SkipNext();
        if (!Win32.OpenClipboard(_hwnd)) return;
        try
        {
            Win32.EmptyClipboard();
            foreach (var name in Markers)
            {
                var format = Win32.RegisterClipboardFormat(name);
                var mem = CopyToGlobal([]);
                if (format != 0 && mem != IntPtr.Zero) Win32.SetClipboardData(format, mem);
            }
            foreach (var payload in payloads)
            {
                Win32.SetClipboardData(payload.Format, IntPtr.Zero);
            }
        }
        finally
        {
            Win32.CloseClipboard();
        }
        ClipboardCapture.NoteOwnWrite();
        lock (Gate)
        {
            if (placement != _placement) return;
            _sequence = Win32.GetClipboardSequenceNumber();
            _placedAt = Environment.TickCount64;
        }
    }

    public static void RenderPromised()
    {
        List<ClipPayload> payloads;
        lock (Gate) payloads = _promised.ToList();
        foreach (var payload in payloads) Render(payload.Format);
    }

    public static void Render(uint format)
    {
        var placement = 0;
        var decide = false;
        var rendered = false;
        lock (Gate)
        {
            if (!IsActive) return;
            foreach (var payload in _promised)
            {
                if (payload.Format != format) continue;
                var mem = CopyToGlobal(payload.Data);
                if (mem != IntPtr.Zero) Win32.SetClipboardData(format, mem);
                rendered = true;
                break;
            }
            if (!rendered) return;
            placement = _placement;
            decide = _handledPlacement != placement;
            if (decide) _handledPlacement = placement;
            if (!decide) return;
        }

        var now = Environment.TickCount64;
        var pasted = IsPaste(now);
        int delay;
        lock (Gate)
        {
            if (pasted)
            {
                _replaceStreak = 0;
                delay = 350;
            }
            else
            {
                var readRightAway = _placedAgain && now - _placedAt < 150;
                _replaceStreak = readRightAway ? _replaceStreak + 1 : 0;
                delay = Math.Min(100 << Math.Min(_replaceStreak, 5), 2000);
            }
        }
        _timer?.Dispose();
        var captured = placement;
        var wasPaste = pasted;
        _timer = new Timer(_ =>
        {
            if (_hwnd != IntPtr.Zero)
            {
                Win32.PostMessage(_hwnd, Win32.WM_QUEUE_TICK, new IntPtr(captured), new IntPtr(wasPaste ? 1 : 0));
            }
        }, null, delay, Timeout.Infinite);
    }

    public static void Tick(int placement, bool pasted)
    {
        lock (Gate)
        {
            if (!IsActive || placement != _placement) return;
        }
        if (pasted)
        {
            App.Instance.QueuePasted();
            return;
        }
        if (!HoldsQueueItem()) return;
        lock (Gate) _replacing = true;
        try
        {
            PlaceNow();
        }
        finally
        {
            lock (Gate) _replacing = false;
        }
    }

    public static void ConsumePasted()
    {
        var empty = false;
        lock (Gate)
        {
            if (!IsActive || Entries.Count == 0) return;
            if (PastesNewestFirst) Entries.RemoveAt(Entries.Count - 1);
            else Entries.RemoveAt(0);
            empty = Entries.Count == 0;
        }
        _window?.Update();
        if (empty)
        {
            Stop();
            return;
        }
        if (!HoldsQueueItem()) return;
        LineUp();
    }

    private static void LineUp()
    {
        lock (Gate)
        {
            if (!IsActive) return;
            var next = PastesNewestFirst ? Entries.LastOrDefault() : Entries.FirstOrDefault();
            if (next is null) return;
            _placed = next.Item;
            _promised = ClipboardCapture.Payloads(next.Item, SettingsStore.Current.AlwaysPlainText).ToList();
            _placement++;
            _handledPlacement = -1;
        }
        if (_hwnd != IntPtr.Zero)
        {
            Win32.PostMessage(_hwnd, Win32.WM_QUEUE_PLACE, IntPtr.Zero, IntPtr.Zero);
        }
    }

    private static bool IsPaste(long now)
    {
        long placedAt;
        lock (Gate) placedAt = _placedAt;
        if (_lastKeyDown <= placedAt) return false;
        var sinceKey = now - _lastKeyDown;
        if (sinceKey < 0 || sinceKey >= 1000) return false;
        if (_lastActivation > 0 && now - _lastActivation < 300) return false;
        var ctrl = (Win32.GetAsyncKeyState((int)Win32.VK_CONTROL) & 0x8000) != 0
            || (Win32.GetAsyncKeyState(0xA2) & 0x8000) != 0
            || (Win32.GetAsyncKeyState(0xA3) & 0x8000) != 0;
        return ctrl || sinceKey < 100;
    }

    private static bool HoldsQueueItem()
    {
        lock (Gate)
        {
            if (_sequence != 0 && Win32.GetClipboardSequenceNumber() == _sequence) return true;
        }
        return ClipboardCapture.QueueMarkersPresent();
    }

    private static bool OwnsLocked() => _sequence != 0 && Win32.GetClipboardSequenceNumber() == _sequence;

    private static IntPtr CopyToGlobal(byte[] bytes)
    {
        var mem = Win32.GlobalAlloc(Win32.GMEM_MOVEABLE, (nuint)Math.Max(1, bytes.Length));
        if (mem == IntPtr.Zero) return IntPtr.Zero;
        var locked = Win32.GlobalLock(mem);
        if (bytes.Length > 0) Marshal.Copy(bytes, 0, locked, bytes.Length);
        Win32.GlobalUnlock(mem);
        return mem;
    }
}
